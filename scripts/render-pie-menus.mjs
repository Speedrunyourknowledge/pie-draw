// Renders the help panel's pie menu pictures (MENU_PREVIEWS, drawn by PieMenuPreview) to SVG files
// for the README and rewrites the README's picture table, so the docs match the app.
// Run with `npm run docs:pies` after changing a menu's layout, icons or styles.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { createServer } from 'vite';

const OUT_DIR = 'docs/pie-menus';
const SIZE = 210; // same as the help panel
const START = '<!-- pie-menus:start (generated by `npm run docs:pies`) -->';
const END = '<!-- pie-menus:end -->';

/** The page's color tokens and the pie menu rules, cut from the app's stylesheet. */
async function pieCss() {
  const css = await readFile('src/index.css', 'utf8');
  const root = css.match(/:root \{[^}]*\}/)?.[0];
  const from = css.indexOf('/* ---- pie menu ---- */');
  const to = css.indexOf('/* ----', from + 1);
  if (!root || from < 0 || to < 0) throw new Error('src/index.css: :root or the pie menu section not found');
  // Static pictures: no fade-in, and no shadow to clip at the image edge (as in the help panel).
  return `${root}\n${css.slice(from, to)}\n.pie, .pie-sub { animation: none; }\n.pie-backdrop { filter: none; }`;
}

const server = await createServer({ server: { middlewareMode: true }, appType: 'custom', logLevel: 'error' });
try {
  const { PieMenuPreview } = await server.ssrLoadModule('/src/interaction/PieMenuPreview.tsx');
  const { MENU_PREVIEWS } = await server.ssrLoadModule('/src/interaction/pieMenuConfig.ts');
  const style = `<style>${await pieCss()}</style>`;

  await mkdir(OUT_DIR, { recursive: true });
  for (const { id, items } of MENU_PREVIEWS) {
    const svg = renderToStaticMarkup(createElement(PieMenuPreview, { items })).replace(
      /^<svg /,
      `<svg width="${SIZE}" height="${SIZE}" `,
    );
    await writeFile(`${OUT_DIR}/${id}.svg`, svg.replace(/>/, `>${style}`) + '\n');
  }

  const cells = (f) => `| ${MENU_PREVIEWS.map(f).join(' | ')} |`;
  const table = [
    cells(({ id, caption }) => `<img src="${OUT_DIR}/${id}.svg" width="${SIZE}" alt="Pie menu: ${caption}">`),
    cells(() => ':-:'),
    cells(({ caption }) => caption),
  ].join('\n');

  const readme = await readFile('README.md', 'utf8');
  const a = readme.indexOf(START), b = readme.indexOf(END);
  if (a < 0 || b < a) throw new Error(`README.md: add the markers\n${START}\n${END}\nwhere the pictures go`);
  await writeFile('README.md', `${readme.slice(0, a + START.length)}\n${table}\n${readme.slice(b)}`);
  console.log(`Wrote ${MENU_PREVIEWS.length} pictures to ${OUT_DIR}/ and updated README.md`);
} finally {
  await server.close();
}
