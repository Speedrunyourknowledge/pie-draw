// Renders the help panel's gesture reference (GestureList) to a PNG for the README and rewrites the
// README's picture, so the docs match the app. Uses headless Chrome for the screenshot (set CHROME to
// its path if it isn't in the default macOS location).
// Run with `npm run docs:gestures` after changing the gesture set, its hints, or the example strokes.
import { execFileSync } from 'node:child_process';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { createServer } from 'vite';

const OUT = 'docs/gesture-guide.png';
const WIDTH = 860; // the panel's width in the app
const CHROME = process.env.CHROME ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const START = '<!-- gesture-guide:start (generated by `npm run docs:gestures`) -->';
const END = '<!-- gesture-guide:end -->';

// The panel as it looks in the app, laid out as a static page: no backdrop, scrolling or shadow.
const PAGE_CSS = `
html, body, #root { height: auto; overflow: visible; }
.help { width: ${WIDTH}px; max-height: none; overflow: visible; box-shadow: none; border-radius: 0; }`;

const chrome = (...args) =>
  execFileSync(CHROME, ['--headless=new', '--disable-gpu', '--hide-scrollbars', ...args], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });

const server = await createServer({ server: { middlewareMode: true }, appType: 'custom', logLevel: 'error' });
const dir = await mkdtemp(join(tmpdir(), 'gesture-guide-'));
try {
  const { GestureList } = await server.ssrLoadModule('/src/ui/GestureGuide.tsx');
  const body = renderToStaticMarkup(
    createElement('div', { className: 'help gesture-guide' }, createElement('header', { className: 'help-head' }, createElement('h2', null, 'Gestures')), createElement(GestureList)),
  );
  const css = await readFile('src/index.css', 'utf8');
  const html = (script = '') =>
    `<!doctype html><meta charset="utf-8"><style>${css}${PAGE_CSS}</style><body>${body}${script}</body>`;

  // Measure the panel's height first, so the screenshot is cropped to it.
  const page = join(dir, 'guide.html');
  await writeFile(page, html('<script>document.body.dataset.h = Math.ceil(document.querySelector(".help").getBoundingClientRect().height)</script>'));
  const height = Number(chrome('--dump-dom', `file://${page}`).match(/data-h="(\d+)"/)?.[1]);
  if (!height) throw new Error('Could not measure the gesture reference');

  await writeFile(page, html());
  chrome('--force-device-scale-factor=2', `--window-size=${WIDTH},${height}`, `--screenshot=${resolve(OUT)}`, `file://${page}`);

  const picture = `<img src="${OUT}" width="${WIDTH}" alt="Gesture reference: every gesture, where it starts and which way it goes">`;
  const readme = await readFile('README.md', 'utf8');
  const a = readme.indexOf(START), b = readme.indexOf(END);
  if (a < 0 || b < a) throw new Error(`README.md: add the markers\n${START}\n${END}\nwhere the picture goes`);
  await writeFile('README.md', `${readme.slice(0, a + START.length)}\n${picture}\n${readme.slice(b)}`);
  console.log(`Wrote ${OUT} (${WIDTH}×${height}) and updated README.md`);
} finally {
  await rm(dir, { recursive: true, force: true });
  await server.close();
}
